#!/bin/bash
# Build LineageOS 14.1 for vivo Xplay6 (PD1610).
# This script is a REAL build pipeline, but it CANNOT complete on this machine
# as-is: see the explicit HARD REQUIREMENTS below. Each missing input causes a
# clean stop with an actionable message instead of a fake "build succeeded".
set -euo pipefail

BRANCH="cm-14.1"                 # Android 7.1 / SDK 25, matches stock
ROOT="${ANDROID_ROOT:-$HOME/android/lineage}"
DEVICE_TREE="$ROOT/device/vivo/pd1610"
KERNEL_TREE="$ROOT/kernel/vivo/msm8996"
JOBS="$(nproc 2>/dev/null || echo 4)"

echo "=== HARD REQUIREMENTS (stop here if any is unmet) ==="
echo "1. Linux host (Ubuntu 18.04/20.04). Android cannot be built on Windows."
echo "2. >= 200 GB free disk, >= 16 GB RAM, openjdk-8-jdk, git, repo, ccache."
echo "3. Kernel source for LA.HB.1.3.2-09200-8x96.0 in $KERNEL_TREE"
echo "   (vivo GPL release; NO public android_kernel_vivo_msm8996 exists)."
echo "4. This device tree installed at $DEVICE_TREE"
echo "5. vendor/vivo/pd1610 generated by ./extract-files.sh against the phone."
echo "6. *** A FLASHABLE, SIGNED BOOT *** -- see the last section of this file."
echo

for c in git repo java make gcc python3; do
    command -v "$c" >/dev/null 2>&1 || { echo "MISSING: $c"; exit 1; }
done
FREE_GB=$(df -BG --output=avail "$ROOT" 2>/dev/null | tail -1 | tr -dc '0-9')
[ -n "$FREE_GB" ] && [ "$FREE_GB" -lt 200 ] && {
    echo "MISSING: only ${FREE_GB} GB free (need >= 200 GB)"; exit 1; }

[ -d "$KERNEL_TREE" ] || { echo "MISSING: kernel source $KERNEL_TREE"; exit 1; }
[ -d "$DEVICE_TREE" ] || { echo "MISSING: device tree $DEVICE_TREE"; exit 1; }
[ -d "$ROOT/vendor/vivo/pd1610" ] || {
    echo "MISSING: vendor blobs, run: cd $DEVICE_TREE && ./extract-files.sh"; exit 1; }

echo "=== init source ==="
mkdir -p "$ROOT" && cd "$ROOT"
[ -d .repo ] || repo init -u https://github.com/LineageOS/android.git -b "$BRANCH"
repo sync -c -j"$JOBS" --force-sync --no-clone-bundle --no-tags

echo "=== local manifests (add kernel + this device + vendor) ==="
mkdir -p .repo/local_manifests
cat > .repo/local_manifests/pd1610.xml <<EOF
<manifest>
  <project name="android_kernel_vivo_msm8996" path="kernel/vivo/msm8996" remote="github" revision="$BRANCH" />
  <project name="android_device_vivo_pd1610" path="device/vivo/pd1610" remote="github" revision="$BRANCH" />
</manifest>
EOF
echo "Edit .repo/local_manifests/pd1610.xml to point at YOUR repos, then re-sync."

echo "=== build ==="
source build/envsetup.sh
breakfast pd1610
ccache -M 50G
brunch pd1610 -j"$JOBS"

echo "=== BEFORE YOU FLASH ==="
echo "The resulting boot.img CANNOT boot this phone:"
echo "  * stock aboot verifies a vivo DER/X.509 signature chain on boot;"
echo "    changing any byte in [0,0xE30000) of boot loops at the logo (measured)."
echo "  * stock boot's fstab.qcom has 'wait,verify' on /system and /oem;"
echo "    the device trusts a vivo verity key we do not possess."
echo "You therefore need an OFFICIAL-SIGNED ENGINEERING BOOT (eng.root) whose"
echo "fstab disables verity, plus a matching system. Flashing only system.img"
echo "onto the stock user build will NOT start. Do not skip this check."
